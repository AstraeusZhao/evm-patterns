export function initialLocale(): Locale {
  try {
    const stored = localStorage.getItem('evm-patterns-language')
    if (languages.some((item) => item.id === stored)) return stored as Locale
  } catch {
    /* Use the default when storage is unavailable. */
  }
  return 'en-GB'
}

export function localiseTag(tag: string, t: Messages) {
  const labels: Record<string, string> = {
    签名: t.signature,
    代理: t.proxy,
    重入: t.reentrancy,
    拍卖: t.auction,
  }
  return labels[tag] ?? tag
}
